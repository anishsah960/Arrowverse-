export function getLevel(levelId: number): Level {
  if (levelId <= HANDCRAFTED_LEVELS.length) {
    return ensureLevelSolvable(HANDCRAFTED_LEVELS[levelId - 1]);
  }

  // Scaling procedural levels beyond 100 handcrafted ones
  let width = 8;
  let height = 8;
  let diff: LevelDifficulty = 'expert';

  if (levelId <= 120) {
    width = 8;
    height = 8;
    diff = 'expert';
  } else if (levelId <= 200) {
    width = 9;
    height = 9;
    diff = 'expert';
  } else {
    width = 10;
    height = 10;
    diff = 'expert';
  }

  return generateProceduralLevel(levelId, width, height, diff);
}

// Generate a deterministic daily puzzle based on date string (e.g. "2026-08-08")
export function getDailyLevel(dateStr: string): Level {
  let seed = 0;
  for (let i = 0; i < dateStr.length; i++) {
    seed = (seed << 5) - seed + dateStr.charCodeAt(i);
    seed |= 0;
  }
  const absSeed = Math.abs(seed);
  const width = 5 + (absSeed % 4); // 5, 6, 7, or 8
  const height = width;
  const difficulties: LevelDifficulty[] = ['medium', 'hard', 'expert'];
  const difficulty = difficulties[absSeed % difficulties.length];

  return generateProceduralLevel(9999 + absSeed % 1000, width, height, difficulty, true, dateStr);
}

