// Helper function to build concise level definitions
function createLevel(
  id: number,
  title: string,
  width: number,
  height: number,
  difficulty: LevelDifficulty,
  arrowsData: [number, number, Direction, number][]
): Level {
  return {
    id,
    title: `Level ${id}: ${title}`,
    width,
    height,
    maxLives: 5,
    difficulty,
    arrows: arrowsData.map(([x, y, direction, colorIndex], i) => ({
      id: `l${id}-${i + 1}`,
      x,
      y,
      direction,
      colorIndex,
    })),
  };
}

